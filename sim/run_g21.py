"""G2.1 independent vectors + real GW5A RAM + signed ROM-to-UART regression.

Run: python -I sim/run_g21.py
Golden values are checked, never regenerated by this regression.
Reuses the G1 tool launcher only; G1 test definitions remain unchanged.
"""
import importlib.util
import json
from pathlib import Path
import subprocess
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "sim/g21_results/signed"


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, ROOT/path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, command in [
        ("python_vectors", ["sim/gen_g21_vectors.py"]),
        ("python_golden", ["src/g21_reference.py", "--check"]),
    ]:
        result = subprocess.run([sys.executable, "-I", *command], cwd=ROOT,
                                capture_output=True, text=True)
        (OUT/(name+".log")).write_text(result.stdout+result.stderr, encoding="utf-8")
        print(result.stdout, end="", flush=True)
        if result.returncode:
            print(result.stderr)
            return result.returncode
    runner = load("g1_launcher", "sim/run_g1.py")
    runner.OUT = OUT
    runner.TESTS = {
        "preprocess": ("tb_g21_preprocess", "G21 PREPROCESS PASS", []),
        "signed_features": ("tb_g21_signed_features", "G21 SIGNED FEATURES PASS", []),
        "signed_uart": ("tb_g21_rom_uart", "G21 ROM UART PASS", []),
        "signed_uart_injected": ("tb_g21_rom_uart", "G21 ROM UART PASS", ["+INJECT_CLASS"]),
    }
    result = runner.main()
    if result:
        return result
    decoder = load("uart_decoder", "src/uart_decode.py")
    golden = json.loads((ROOT/"src/golden/g21_signed/expected_packets.json").read_text())
    capture = (OUT/"uart_signed.bin").read_bytes()
    ok, lines = decoder.check_capture(capture, golden)
    if not ok:
        raise AssertionError("\n".join(lines))
    # No mode guessing: a signed capture must fail against the frozen G1 golden.
    legacy = json.loads((ROOT/"src/golden/expected_packets.json").read_text())
    assert not decoder.check_capture(capture, legacy)[0], "stale legacy golden was accepted"
    decoded = list(decoder.decode_stream(capture))
    assert any(v < 0 for _, packet in decoded for v in packet["features"])
    # Checker must reject corrupted signed features even with a valid checksum.
    bad = bytearray(capture)
    bad[11] ^= 0x80
    bad[32] = sum(bad[2:32]) % 256
    assert not decoder.check_capture(bytes(bad), golden)[0]
    injected = list(decoder.decode_stream((OUT/"uart_signed_injected.bin").read_bytes()))
    assert [p["class"] for _, p in injected] == [0,1,2,3,0,1,2]
    (OUT/"signed_decoder.log").write_text("\n".join(lines)+
        "\nPASS signed decoding, stale golden rejection, corruption rejection, injected classes\n", encoding="utf-8")
    with (OUT/"summary.txt").open("a", encoding="utf-8") as f:
        f.write("python_vectors: PASS\npython_golden: PASS\nsigned_decoder: PASS\n")
    print("G21 ALL PASS: 4 Questa + 4 Python groups; all 231 UART bytes strict", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
